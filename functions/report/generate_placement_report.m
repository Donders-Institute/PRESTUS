function report_path = generate_placement_report(parameters, mode)
% GENERATE_PLACEMENT_REPORT  Stand-alone HTML report of a transducer placement
%
% Written after preproc_transducer_placement for every placement mode
% (placement.report, default true), independently of the simulation report.
% Sections:
%   Placement  - mode, target, transducer and focus positions (voxel and RAS
%                mm), focus–target and transducer–focus distances
%   T1 overlay - the placement QC figure (plot_placement_t1_overlay; drawn
%                here for modes that do not produce one)
%   PlanTUS    - for mode 'plantus': the criteria evaluation written by
%                plantus_evaluation.py (diagnostics, criterion values and
%                percentiles at the placed spot, weight sweep, figures)
%   Configuration - the placement config struct
%
% Use as:
%   report_path = generate_placement_report(parameters)
%   report_path = generate_placement_report(parameters, mode)
%
% Input:
%   parameters - (1,1) parameters struct after transducer placement
%   mode       - placement mode (default: parameters.placement.mode)
%
% Output:
%   report_path - <io.dir_reports>/sub-XXX_placement_<mode><affix>.html, or ''
%                 on failure (failures are reported as warnings, never errors)
%
% See also: PREPROC_TRANSDUCER_PLACEMENT, PLOT_PLACEMENT_T1_OVERLAY,
%           GENERATE_SIMULATION_REPORT

arguments
    parameters (1,1) struct
    mode char = ''
end

report_path = '';

try
    parameters = resolve_io_dirs(parameters);
    if ~isfield(parameters, 'io') || ~isfield(parameters.io, 'dir_reports') ...
            || isempty(parameters.io.dir_reports)
        fprintf('Placement report skipped: no output directory (io.dir_output or path.sim).\n');
        return
    end
    if isempty(mode)
        mode = 'manual';
        if isfield(parameters, 'placement') && isfield(parameters.placement, 'mode') ...
                && ~isempty(parameters.placement.mode)
            mode = lower(char(parameters.placement.mode));
        end
    end
    subject_id = parameters.subject_id;
    affix = '';
    if isfield(parameters.io, 'output_affix'); affix = parameters.io.output_affix; end
    style_opts = report_styles.options(parameters);

    if ~isfolder(parameters.io.dir_reports); mkdir(parameters.io.dir_reports); end
    report_path = fullfile(parameters.io.dir_reports, ...
        sprintf('sub-%03d_placement_%s%s.html', subject_id, mode, affix));

    t1_header = [];
    t1_file = fullfile(parameters.path.anat, sprintf(parameters.path.t1_pattern, subject_id));
    t1_hits = dir(t1_file);
    if ~isempty(t1_hits)
        t1_header = niftiinfo(fullfile(t1_hits(1).folder, t1_hits(1).name));
    end
    target = placement_target(parameters, mode);

    h = {};
    h{end+1} = '<!DOCTYPE html>';
    h{end+1} = sprintf('<html lang="en" data-theme="light" data-style="%s">', style_opts.name);
    h{end+1} = '<head><meta charset="UTF-8">';
    h{end+1} = '<meta name="viewport" content="width=device-width, initial-scale=1.0">';
    h{end+1} = ['<script>try{var t=localStorage.getItem("prestus-theme")||' ...
        '((window.matchMedia&&matchMedia("(prefers-color-scheme:dark)").matches)?"dark":"light");' ...
        'document.documentElement.setAttribute("data-theme",t);}catch(e){}</script>'];
    h{end+1} = sprintf('<title>PRESTUS Placement — sub-%03d %s%s</title>', subject_id, mode, affix);
    h{end+1} = ['<style>' css_styles_base() report_styles.css(style_opts) local_css() '</style>'];
    h{end+1} = '</head><body><a id="top"></a>';

    sections = {
        'Placement',     @() build_placement_section(parameters, mode, target, t1_header), true, 'placement'
        'T1 overlay',    @() build_overlay_section(parameters, mode, affix),               true, 'overlay'
    };
    if strcmp(mode, 'plantus')
        sections(end+1, :) = {'PlanTUS criteria evaluation', ...
            @() build_plantus_section(parameters, target), true, 'plantus'};
    end
    sections(end+1, :) = {'Placement configuration', ...
        @() build_config_section(parameters), false, 'config'};

    h{end+1} = build_header(parameters, mode, affix, sections(:, [1 4]));
    for i = 1:size(sections, 1)
        try
            h{end+1} = html_utils.collapsible(sections{i, 1}, sections{i, 2}(), ...
                sections{i, 3}, sections{i, 4}); %#ok<AGROW>
        catch ME
            h{end+1} = html_utils.section_error(sections{i, 1}, ME); %#ok<AGROW>
        end
    end

    h{end+1} = sprintf('<footer><p>Generated by PRESTUS %s</p></footer>', ...
        datestr(now, 'yyyy-mm-dd HH:MM:SS')); %#ok<TNOW1,DATST>
    h{end+1} = html_utils.lightbox();
    h{end+1} = report_scripts.common();
    h{end+1} = report_styles.script(style_opts);
    h{end+1} = '</body></html>';

    fid = fopen(report_path, 'w', 'n', 'UTF-8');
    if fid == -1
        warn('generate_placement_report:fileOpen', 'Cannot open %s for writing.', report_path);
        report_path = '';
        return
    end
    fprintf(fid, '%s\n', h{:});
    fclose(fid);
    fprintf('Placement report saved to: %s\n', report_path);

catch ME
    warn('generate_placement_report:failed', ...
        'Placement report failed: %s\n%s', ME.message, getReport(ME, 'extended'));
    report_path = '';
end
end

% ── Header ──────────────────────────────────────────────────────────────
function html = build_header(parameters, mode, affix, toc)
    html = '<section class="report-section" id="header">';
    html = [html '<h1>PRESTUS Placement Report</h1><table class="info-table">'];
    html = [html kv('Subject', sprintf('sub-%03d', parameters.subject_id))];
    html = [html kv('Placement mode', html_utils.escape(mode))];
    if ~isempty(affix); html = [html kv('Affix', html_utils.escape(affix))]; end
    html = [html kv('Generated', datestr(now, 'yyyy-mm-dd HH:MM:SS'))]; %#ok<TNOW1,DATST>
    html = [html '</table><p class="note">'];
    links = cellfun(@(t, id) sprintf('<a href="#%s">%s</a>', id, html_utils.escape(t)), ...
        toc(:, 1), toc(:, 2), 'UniformOutput', false);
    html = [html strjoin(links', ' &middot; ') '</p></section>'];
end

% ── Placement: target and positions ─────────────────────────────────────
function html = build_placement_section(parameters, mode, target, t1_header)
    html = '<table class="info-table">';
    if ~isempty(target.name); html = [html kv('Target', html_utils.escape(target.name))]; end
    if ~isempty(target.mni);  html = [html kv('Target (MNI mm)', fmt_vec(target.mni, '%.1f'))]; end
    if ~isempty(target.ras);  html = [html kv('Target (subject RAS mm)', fmt_vec(target.ras, '%.1f'))]; end
    html = [html '</table>'];

    html = [html '<table class="data-table"><thead><tr><th>Transducer</th>' ...
        '<th>trans_pos (vox)</th><th>focus_pos (vox)</th>' ...
        '<th>trans_pos (RAS mm)</th><th>focus_pos (RAS mm)</th>' ...
        '<th>Transducer–focus [mm]</th><th>Focus–target [mm]</th></tr></thead><tbody>'];
    for ti = 1:numel(parameters.transducer)
        tr = parameters.transducer(ti);
        tp = field_or(tr, 'trans_pos', []);
        fp = field_or(tr, 'focus_pos', []);
        tp_ras = field_or(tr, 'trans_pos_ras', []);
        fp_ras = field_or(tr, 'focus_pos_ras', []);
        if isempty(tp_ras) && ~isempty(tp) && ~isempty(t1_header)
            tp_ras = transform_coordinates(parameters, double(tp(:)'), 'grid', 'ras_plus', t1_header);
        end
        if isempty(fp_ras) && ~isempty(fp) && ~isempty(t1_header)
            fp_ras = transform_coordinates(parameters, double(fp(:)'), 'grid', 'ras_plus', t1_header);
        end
        name = sprintf('%d', ti);
        if isfield(tr, 'name') && ~isempty(tr.name)
            name = sprintf('%d (%s)', ti, html_utils.escape(char(string(tr.name))));
        end
        d_tf = ''; d_ft = '';
        if ~isempty(tp_ras) && ~isempty(fp_ras); d_tf = sprintf('%.1f', norm(tp_ras(:) - fp_ras(:))); end
        if ~isempty(fp_ras) && ~isempty(target.ras); d_ft = sprintf('%.1f', norm(fp_ras(:) - target.ras(:))); end
        html = [html sprintf('<tr><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>', ...
            name, fmt_vec(tp, '%d'), fmt_vec(fp, '%d'), fmt_vec(tp_ras, '%.1f'), ...
            fmt_vec(fp_ras, '%.1f'), d_tf, d_ft)]; %#ok<AGROW>
    end
    html = [html '</tbody></table>'];
    if strcmp(mode, 'manual')
        html = [html '<p class="note">Manual placement: positions as configured ' ...
            '(placement.manual.coordinate_space converted to T1 voxels).</p>'];
    end
end

% ── T1 overlay ──────────────────────────────────────────────────────────
function html = build_overlay_section(parameters, mode, affix)
    img = fullfile(parameters.io.dir_img, ...
        sprintf('sub-%03d_placement_%s%s.png', parameters.subject_id, mode, affix));
    tr = parameters.transducer(1);
    if ~isfile(img) && ~isempty(field_or(tr, 'trans_pos', [])) && ~isempty(field_or(tr, 'focus_pos', []))
        % Modes without their own QC figure (manual, localite)
        plot_placement_t1_overlay(parameters, tr.trans_pos, tr.focus_pos, mode);
    end
    html = html_utils.embed_image(img, 'Placement on T1', ...
        'Transducer (red) and focus (green) on the subject T1; top row through the transducer, bottom row through the focus.');
    if isempty(html)
        html = '<p class="placeholder">No T1 overlay figure found.</p>';
    end
end

% ── PlanTUS evaluation ──────────────────────────────────────────────────
function html = build_plantus_section(parameters, target)
    eval_dir = fullfile(parameters.path.seg, 'PlanTUS', ...
        sprintf('sub-%03d', parameters.subject_id), target.name);
    eval_file = fullfile(eval_dir, 'plantus_evaluation.json');
    if ~isfile(eval_file)
        html = sprintf(['<p class="placeholder">No PlanTUS evaluation found at %s. ' ...
            'It is written by the PlanTUS launchers when placement.plantus.evaluate and ' ...
            'save_metrics are true; for an existing plantus_metrics.mat run ' ...
            '<code>python functions/neuronav/plantus_evaluation.py &lt;plantus_metrics.mat&gt;</code>.</p>'], ...
            html_utils.escape(eval_file));
        return
    end
    ev = jsondecode(fileread(eval_file));
    html = '';

    % Diagnostics
    flags = to_cell(ev.flags);
    if isempty(flags)
        html = [html '<div class="pl-flag pl-ok">No issues flagged.</div>'];
    end
    for i = 1:numel(flags)
        f = flags{i};
        html = [html sprintf('<div class="pl-flag pl-%s"><b>%s</b> %s</div>', ...
            f.level, html_utils.escape(f.level), html_utils.escape(f.message))]; %#ok<AGROW>
    end

    % Summary
    p = ev.placed;
    rank = 'not eligible';
    if ~isempty(p.rank); rank = sprintf('%d of %d eligible', p.rank, ev.n_eligible); end
    html = [html '<table class="info-table">'];
    html = [html kv('Placed vertex', sprintf('%d (%s selection)', p.vertex, html_utils.escape(p.selection_mode)))];
    html = [html kv('Placed spot (skin, RAS mm)', fmt_vec(num(p.ras_mm), '%.1f'))];
    html = [html kv('Rank under configured weights', rank)];
    html = [html kv('Skin–target distance', sprintf('%s mm (optimal %.1f mm, allowed %.1f–%.1f mm)', ...
        fmt_num(p.skin_target_distance_mm, '%.1f'), ev.optimal_distance_mm, ev.distance_range_mm))];
    html = [html kv('Eligible skin vertices', sprintf('%d of %d', ev.n_eligible, ev.n_vertices))];
    html = [html kv('Weight sweep', sprintf('%d distinct spots across %d weight sets; up to %s mm from the placed spot', ...
        ev.sweep_distinct_spots, numel(to_cell(ev.sweep)), fmt_num(ev.sweep_max_dist_to_placed_mm, '%.0f')))];
    html = [html '</table>'];

    % Criteria at the placed spot
    crit = to_cell(ev.criteria);
    html = [html '<h3>Criteria at the placed spot</h3><table class="data-table"><thead><tr>' ...
        '<th>Criterion</th><th>Weight</th><th>Placed</th><th>% eligible better</th>' ...
        '<th>Eligible min / median / max</th><th>Defined at</th></tr></thead><tbody>'];
    for i = 1:numel(crit)
        c = crit{i};
        pc = p.criteria.(c.key);
        dir_txt = 'lower is better';
        if c.higher_is_better; dir_txt = 'higher is better'; end
        html = [html sprintf(['<tr><td>%s <span class="note">(%s)</span></td><td>%s</td>' ...
            '<td>%s %s</td><td>%s</td><td>%s / %s / %s</td><td>%s%%</td></tr>'], ...
            html_utils.escape(c.label), dir_txt, fmt_num(c.weight, '%.2f'), ...
            fmt_num(pc.value, '%.1f'), c.unit, fmt_num(pc.pct_better, '%.0f'), ...
            fmt_num(c.eligible_min, '%.1f'), fmt_num(c.eligible_median, '%.1f'), ...
            fmt_num(c.eligible_max, '%.1f'), fmt_num(100 * num(c.eligible_defined_fraction), '%.0f'))]; %#ok<AGROW>
    end
    html = [html '</tbody></table>'];

    % Figures
    html = [html '<div class="image-grid image-grid--wide">'];
    html = [html html_utils.embed_image(fullfile(eval_dir, 'plantus_criteria_maps.png'), ...
        'PlanTUS criteria maps', ['Each criterion and the composite score on the skin. ' ...
        'Grey: excluded (avoidance mask or outside the distance range). Star: placed spot.'])];
    html = [html html_utils.embed_image(fullfile(eval_dir, 'plantus_weight_sensitivity.png'), ...
        'PlanTUS weight sensitivity', ['Spot chosen under each weight set, with each ' ...
        'criterion''s value and the % of eligible spots that are better.'])];
    html = [html '</div>'];

    % Sweep table
    sweep = to_cell(ev.sweep);
    keys = cellfun(@(c) c.key, crit, 'UniformOutput', false);
    html = [html '<h3>Weight sweep</h3><table class="data-table"><thead><tr><th>Weight set</th>' ...
        '<th>Weights (' strjoin(keys, ' / ') ')</th><th>Vertex</th><th>&Delta; to placed [mm]</th>' ...
        '<th>Rank (configured)</th>'];
    for i = 1:numel(crit)
        html = [html sprintf('<th>%s [%s]</th>', html_utils.escape(crit{i}.label), crit{i}.unit)]; %#ok<AGROW>
    end
    html = [html '</tr></thead><tbody>'];
    for i = 1:numel(sweep)
        r = sweep{i};
        w = cellfun(@(k) fmt_num(r.(['w_' k]), '%.2f'), keys, 'UniformOutput', false);
        html = [html sprintf('<tr><td>%s</td><td>%s</td><td>%d</td><td>%s</td><td>%d</td>', ...
            html_utils.escape(r.weight_set), strjoin(w, ' / '), r.vertex, ...
            fmt_num(r.dist_to_placed_mm, '%.1f'), r.rank_under_configured)]; %#ok<AGROW>
        for k = 1:numel(keys)
            html = [html sprintf('<td>%s <span class="note">(%s%%)</span></td>', ...
                fmt_num(r.([keys{k} '_value']), '%.1f'), ...
                fmt_num(r.([keys{k} '_pct_better']), '%.0f'))]; %#ok<AGROW>
        end
        html = [html '</tr>']; %#ok<AGROW>
    end
    html = [html '</tbody></table>'];
    html = [html sprintf(['<p class="note">Rows are re-scored from %s with the launchers'' ' ...
        'composite score. Values in brackets: %% of eligible spots that are better (0 = best). ' ...
        'Planning scene for Connectome Workbench: %s.</p>'], ...
        html_utils.escape(ev.metrics_file), html_utils.escape(fullfile(eval_dir, 'scene.scene')))];
end

% ── Configuration ───────────────────────────────────────────────────────
function html = build_config_section(parameters)
    if ~isfield(parameters, 'placement')
        html = '<p class="placeholder">No placement configuration.</p>';
        return
    end
    html = ['<pre>' html_utils.escape(jsonencode(parameters.placement, 'PrettyPrint', true)) '</pre>'];
end

% ── Helpers ─────────────────────────────────────────────────────────────
function t = placement_target(parameters, mode)
% Target name / MNI / RAS from the mode's config struct, where available.
    t = struct('name', '', 'mni', [], 'ras', []);
    if ~isfield(parameters, 'placement') || ~isfield(parameters.placement, mode)
        return
    end
    c = parameters.placement.(mode);
    if ~isstruct(c); return; end
    if isfield(c, 'target_name') && ~isempty(c.target_name); t.name = char(c.target_name); end
    if isfield(c, 'mni_target_mm') && ~isempty(c.mni_target_mm); t.mni = c.mni_target_mm(:)'; end
    if strcmp(mode, 'mni') && isfield(c, 'focus_pos_mm') && ~isempty(c.focus_pos_mm)
        t.mni = c.focus_pos_mm(:)';
    end
    if isfield(c, 'target_ras') && ~isempty(c.target_ras); t.ras = c.target_ras(:)'; end
end

function v = field_or(s, f, default)
    v = default;
    if isfield(s, f) && ~isempty(s.(f)); v = s.(f); end
end

function s = kv(k, v)
    s = sprintf('<tr><th>%s</th><td>%s</td></tr>', html_utils.escape(k), v);
end

function s = fmt_vec(v, fmt)
    if isempty(v); s = ''; return; end
    s = ['[' strjoin(arrayfun(@(x) fmt_num(x, fmt), v(:)', 'UniformOutput', false), ', ') ']'];
end

function s = fmt_num(x, fmt)
% Format a number; JSON null (empty) and NaN print as n/a.
    x = num(x);
    if isempty(x) || ~isfinite(x); s = 'n/a'; return; end
    if strcmp(fmt, '%d'); x = round(x); end
    s = sprintf(fmt, x);
end

function x = num(x)
    if iscell(x)
        x = cellfun(@(e) ifelse_empty(e), x);
    end
end

function y = ifelse_empty(e)
    if isempty(e); y = NaN; else; y = double(e); end
end

function c = to_cell(x)
% jsondecode returns struct arrays for uniform objects and cells otherwise.
    if isempty(x); c = {}; elseif iscell(x); c = x(:)'; else; c = num2cell(x(:)'); end
end

