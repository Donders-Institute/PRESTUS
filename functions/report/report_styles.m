classdef report_styles
% REPORT_STYLES  Alternative visual skins for the PRESTUS HTML reports
%
% Every skin is a CSS layer on top of css_styles_base(), scoped under
% html[data-style="<name>"]. Skins only change presentation (colour, type,
% density, panel framing); they never add or remove report content, so a
% report can carry all skins at once and switch between them live.
%
% Available skins:
%   instrument - current default design (css_styles_base only, no overrides)
%   classic    - look of the pre-v0.6.1 reports: flat tinted safety cards with
%                a coloured left border, sans-serif values, no verdict banner
%                or group headers, plain figure panels
%   compact    - dense dashboard: small tiles, 3-4 figures per row, tight
%                tables; useful when paging through many runs
%   paper      - print / publication: white, no shadows, thin rules, serif
%                headings, figures without frames, all sections expanded
%
% Selected via the config (defaults shown):
%   modules.report_style: 'instrument'
%   modules.report_style_switcher: 0   % 1 = embed all skins + dropdown
%
% Methods:
%   report_styles.names()          - cell array of skin names
%   report_styles.options(params)  - struct(name, switcher) from parameters
%   report_styles.css(opts)        - CSS to append after css_styles_base()
%   report_styles.switcher(opts)   - <select> markup for the nav bar ('' if off)
%   report_styles.script(opts)     - <script> for the switcher ('' if off)
%
% See also: CSS_STYLES_BASE, GENERATE_SIMULATION_REPORT, PREVIEW_REPORT_STYLES

    methods (Static)

        function n = names()
            n = {'instrument', 'classic', 'compact', 'paper'};
        end

        function opts = options(parameters)
        % options  Resolve skin name + switcher flag, falling back to defaults.
            opts = struct('name', 'instrument', 'switcher', false);
            if isfield(parameters, 'modules')
                m = parameters.modules;
                if isfield(m, 'report_style') && ~isempty(m.report_style)
                    opts.name = lower(char(m.report_style));
                end
                if isfield(m, 'report_style_switcher') && ~isempty(m.report_style_switcher)
                    opts.switcher = logical(m.report_style_switcher);
                end
            end
            if ~ismember(opts.name, report_styles.names())
                warning('report_styles:unknownStyle', ...
                    'Unknown report_style "%s"; using "instrument". Available: %s', ...
                    opts.name, strjoin(report_styles.names(), ', '));
                opts.name = 'instrument';
            end
        end

        function css = css(opts)
        % css  Override CSS for the selected skin, or for all skins when the
        % switcher is enabled. The default skin adds nothing.
            if opts.switcher
                skins = report_styles.names();
            else
                skins = {opts.name};
            end
            css = '';
            for k = 1:numel(skins)
                switch skins{k}
                    case 'classic', css = [css newline report_styles.css_classic()]; %#ok<AGROW>
                    case 'compact', css = [css newline report_styles.css_compact()]; %#ok<AGROW>
                    case 'paper',   css = [css newline report_styles.css_paper()]; %#ok<AGROW>
                end
            end
            if opts.switcher
                css = [css newline '.style-select{font-size:.8rem;padding:5px 8px}'];
            end
        end

        function html = switcher(opts)
            html = '';
            if ~opts.switcher; return; end
            html = '<select class="style-select hide-sm" id="style-select" title="Report style" aria-label="Report style">';
            skins = report_styles.names();
            for k = 1:numel(skins)
                sel = '';
                if strcmp(skins{k}, opts.name); sel = ' selected'; end
                html = [html sprintf('<option value="%s"%s>%s</option>', skins{k}, sel, skins{k})]; %#ok<AGROW>
            end
            html = [html '</select>'];
        end

        function html = script(opts)
        % script  Switcher behaviour: ?style=<name> URL override, remembered
        % choice (localStorage), and auto-expanding all sections for "paper".
            html = '';
            if ~opts.switcher && ~strcmp(opts.name, 'paper'); return; end
            html = ['<script>(function(){var h=document.documentElement,' ...
                's=document.getElementById("style-select");' ...
                'function sync(){if(h.getAttribute("data-style")==="paper"){' ...
                'document.querySelectorAll("details.report-section").forEach(function(d){d.open=true;});}}' ...
                'function set(v){if(!v||(s&&!s.querySelector("option[value=\""+v+"\"]")))return;' ...
                'h.setAttribute("data-style",v);if(s)s.value=v;sync();}' ...
                'if(s){var q=null;try{q=new URLSearchParams(location.search).get("style");}catch(e){}' ...
                'var saved=null;try{saved=localStorage.getItem("prestus-style");}catch(e){}' ...
                'set(q||saved);s.addEventListener("change",function(){set(s.value);' ...
                'try{localStorage.setItem("prestus-style",s.value);}catch(e){}});}' ...
                'sync();})();</script>'];
        end

    end

