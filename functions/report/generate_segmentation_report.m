function report_path = generate_segmentation_report(parameters)
% GENERATE_SEGMENTATION_REPORT  HTML report of the head-model postprocessing
%
% Shows how the SimNIBS segmentation became the simulation medium, one step
% at a time (records of SEG_QC): tissue mapping and smoothing, skull hole
% filling, eyes to water, CSF-based crop, and grid crop. For each step:
%   - before / after / changed-voxel slices through the focus in three
%     planes (interactive: plane, size, voxel read-out on hover)
%   - the voxels moved between tissues, with volumes
% plus tissue volumes after each step, the settings that drive the steps,
% and links to the SimNIBS charm report and the debug report.
%
% Written after the grid stage of every layered run with report.segmentation
% on (default). The records live in <io.dir_cache>/sub-XXX_<medium>_segqc<affix>.mat,
% written when the head model is built; a run that reuses the cached head
% model reuses them.
%
% Use as:
%   report_path = generate_segmentation_report(parameters)
%
% Input:
%   parameters - PRESTUS parameters of the run (layered medium)
%
% Output:
%   report_path - <io.dir_reports>/sub-XXX_<medium>_segmentation_report<affix>.html,
%                 or '' when skipped or failed (failures are warnings only)
%
% See also: SEG_QC, GENERATE_DEBUG_REPORT, PREPROC_HEAD

arguments
    parameters (1,1) struct
end

report_path = '';
try
    if ~strcmp(parameters.simulation.medium, 'layered') || ~report_flag(parameters, 'segmentation')
        return
    end
    parameters = resolve_io_dirs(parameters);
    if ~isfield(parameters.io, 'dir_reports') || isempty(parameters.io.dir_reports)
        return
    end
    subject_id = parameters.subject_id;
    medium = parameters.simulation.medium;
    affix = '';
    if isfield(parameters.io, 'output_affix'); affix = char(parameters.io.output_affix); end
    report_dir = parameters.io.dir_reports;
    if ~isfolder(report_dir); mkdir(report_dir); end
    report_path = fullfile(report_dir, sprintf('sub-%03d_%s_segmentation_report%s.html', subject_id, medium, affix));
    style_opts = report_styles.options(parameters);

    qc_file = seg_qc('file', parameters);
    steps = [];
    qc_info = struct();
    if isfile(qc_file)
        L = load(qc_file, 'steps', 'qc_info');
        steps = L.steps;
        qc_info = L.qc_info;
    end
    if ~isfield(qc_info, 'labels_medium') || isempty(qc_info.labels_medium)
        qc_info.labels_medium = fieldnames(parameters.medium_properties)';
    end
    if ~isfield(qc_info, 'resolution_mm')
        qc_info.resolution_mm = parameters.grid.resolution_mm;
    end
    lab = label_tables(qc_info.labels_medium);

    h = {};
    h{end+1} = '<!DOCTYPE html>';
    h{end+1} = sprintf('<html lang="en" data-theme="light" data-style="%s">', style_opts.name);
    h{end+1} = '<head><meta charset="UTF-8">';
    h{end+1} = '<meta name="viewport" content="width=device-width, initial-scale=1.0">';
    h{end+1} = ['<script>try{var t=localStorage.getItem("prestus-theme")||' ...
        '((window.matchMedia&&matchMedia("(prefers-color-scheme:dark)").matches)?"dark":"light");' ...
        'document.documentElement.setAttribute("data-theme",t);}catch(e){}</script>'];
    h{end+1} = sprintf('<title>PRESTUS Segmentation — sub-%03d%s</title>', subject_id, affix);
    h{end+1} = ['<style>' css_styles_base() report_styles.css(style_opts) local_css() '</style>'];
    h{end+1} = '</head><body><a id="top"></a>';

    sections = cell(0, 4);
    if isempty(steps)
        sections(end+1, :) = {'No postprocessing records', @() build_missing_section(qc_file), true, 'missing'};
    else
        sections(end+1, :) = {'Summary', @() build_summary_section(steps, lab, qc_info), true, 'summary'};
        sections(end+1, :) = {'Steps', @() build_steps_section(steps, lab, qc_info), true, 'steps'};
        sections(end+1, :) = {'Tissue volumes', @() build_volumes_section(steps, lab, qc_info), false, 'volumes'};
    end
    sections(end+1, :) = {'Settings', @() build_settings_section(parameters), false, 'settings'};

    h{end+1} = build_header(parameters, affix, qc_file, qc_info, report_dir, sections(:, [1 4]));
    for i = 1:size(sections, 1)
        try
            h{end+1} = html_utils.collapsible(sections{i, 1}, sections{i, 2}(), ...
                sections{i, 3}, sections{i, 4}); %#ok<AGROW>
        catch MEs
            h{end+1} = html_utils.section_error(sections{i, 1}, MEs); %#ok<AGROW>
        end
    end
    h{end+1} = sprintf('<footer><p>Generated by PRESTUS %s</p></footer>', ...
        char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss')));
    if ~isempty(steps)
        h{end+1} = ['<script type="application/json" id="segqc-data">' ...
            html_utils.script_json(viewer_data(steps, lab)) '</script>'];
        h{end+1} = viewer_script();
    end
    h{end+1} = report_scripts.common();
    h{end+1} = report_styles.script(style_opts);
    h{end+1} = '</body></html>';

    fid = fopen(report_path, 'w', 'n', 'UTF-8');
    if fid == -1
        warning('PRESTUS:segReport:fileOpen', 'Cannot open %s for writing.', report_path);
        report_path = '';
        return
    end
    fprintf(fid, '%s\n', h{:});
    fclose(fid);
    fprintf('Segmentation report saved to: %s\n', report_path);
catch ME
    warning('PRESTUS:segReport:failed', 'Segmentation report failed: %s', ME.message);
    report_path = '';
end
end

% ── Labels ─────────────────────────────────────────────────────────────
function lab = label_tables(labels_medium)
% Names and colours of label values in the two label spaces
    med_names = [{'unassigned'}, cellstr(labels_medium(:)')];
    med_cols = cellfun(@tissue_colour, med_names, 'UniformOutput', false);
    cs = charm_seg_labels();
    names = fieldnames(cs);
    chm_names = {};
    for i = 1:numel(names)
        v = cs.(names{i});
        if isscalar(v) && v >= 0
            chm_names{v+1} = names{i}; %#ok<AGROW>
        end
    end
    chm_names{1} = 'background';
    for i = 1:numel(chm_names)
        if isempty(chm_names{i}); chm_names{i} = sprintf('label %d', i-1); end
    end
    chm_cols = cellfun(@tissue_colour, chm_names, 'UniformOutput', false);
    lab = struct('medium', struct('names', {med_names}, 'colours', {med_cols}), ...
                 'charm',  struct('names', {chm_names}, 'colours', {chm_cols}));
end

function c = tissue_colour(name)
    map = struct('unassigned', '#000000', 'background', '#000000', 'external', '#000000', ...
        'water', '#203a5c', 'brain', '#a493d6', 'wm', '#ece6d8', 'gm', '#8f8f99', 'csf', '#4fa3e0', ...
        'skull', '#f1dfa8', 'skull_cortical', '#fff3cf', 'skull_trabecular', '#d6a23c', ...
        'skin', '#e59a72', 'eye', '#46c6b9', 'blood', '#d23a3a', 'muscle', '#a85656', ...
        'fat', '#f5e663', 'tissue', '#c97f9a');
    if isfield(map, name)
        c = map.(name);
    else
        pal = {'#7fc97f', '#beaed4', '#fdc086', '#386cb0', '#f0027f', '#bf5b17', '#66a61e'};
        c = pal{mod(sum(double(name)), numel(pal)) + 1};
    end
end

function n = label_name(lab, space, v)
    names = lab.(space).names;
    if v + 1 <= numel(names)
        n = names{v+1};
    else
        n = sprintf('label %d', v);
    end
end

% ── Sections ───────────────────────────────────────────────────────────
function html = build_header(parameters, affix, qc_file, qc_info, report_dir, toc)
    html = '<section class="report-section" id="header">';
    html = [html '<h1>PRESTUS Segmentation Report</h1><table class="info-table">'];
    html = [html kv('Subject', sprintf('sub-%03d', parameters.subject_id))];
    if ~isempty(affix); html = [html kv('Affix', html_utils.escape(affix))]; end
    html = [html kv('Simulation resolution', sprintf('%g mm', qc_info.resolution_mm))];
    if isfield(qc_info, 'created')
        html = [html kv('Head model built', html_utils.escape(qc_info.created))];
    end
    m2m = '';
    if isfield(parameters, 'path') && isfield(parameters.path, 'seg') && ~isempty(parameters.path.seg)
        m2m = fullfile(parameters.path.seg, sprintf('m2m_sub-%03d', parameters.subject_id));
        html = [html kv('SimNIBS folder', html_utils.escape(m2m))];
    end
    links = {};
    charm_report = fullfile(m2m, 'charm_report.html');
    if ~isempty(m2m) && isfile(charm_report)
        links{end+1} = sprintf('<a href="%s">SimNIBS charm report</a>', ...
            html_utils.escape(report_link(charm_report, report_dir)));
    end
    base = sprintf('sub-%03d_%s_%%s%s.html', parameters.subject_id, parameters.simulation.medium, affix);
    % linked when the run writes them (they are written after this report)
    expected = struct('report', module_on(parameters, 'generate_report'), ...
        'debug_report', debug_on(parameters) && report_flag(parameters, 'debug'));
    for r = {{'report', 'Simulation report'}, {'debug_report', 'Debug report'}}
        f = fullfile(report_dir, sprintf(base, r{1}{1}));
        if isfile(f) || expected.(r{1}{1})
            links{end+1} = sprintf('<a href="%s">%s</a>', html_utils.escape(report_link(f, report_dir)), r{1}{2}); %#ok<AGROW>
        end
    end
    if ~isempty(links)
        html = [html kv('See also', strjoin(links, ' &middot; '))];
    end
    html = [html kv('Records', html_utils.escape(qc_file))];
    html = [html '</table><p class="note">'];
    tl = cellfun(@(t, id) sprintf('<a href="#%s">%s</a>', id, html_utils.escape(t)), ...
        toc(:, 1), toc(:, 2), 'UniformOutput', false);
    html = [html strjoin(tl', ' &middot; ') '</p></section>'];
end

function html = build_missing_section(qc_file)
    html = sprintf(['<p class="placeholder">No postprocessing records in <code>%s</code>.</p>' ...
        '<p>The head model of this run was loaded from a cache built without records ' ...
        '(<code>report.segmentation: 0</code>, or a PRESTUS version without this report). ' ...
        'Records are written when the head model is built: delete <code>cache/sub-XXX_layered_cropped_smoothed&lt;affix&gt;.mat</code> ' ...
        '(and, with <code>headmodel.reuse_across_placements</code>, the <code>_headmodel_</code> cache) to rebuild it.</p>'], ...
        html_utils.escape(qc_file));
end

function html = build_summary_section(steps, lab, info)
    ml = info.resolution_mm^3 / 1000;
    html = ['<p>Each row is one step from the SimNIBS segmentation to the medium the simulation uses. ' ...
        '<em>Changed</em> counts voxels whose tissue the step changed; <em>Largest moves</em> lists ' ...
        'the largest tissue-to-tissue changes.</p>'];
    html = [html '<table class="data-table"><thead><tr><th>#</th><th>Step</th>' ...
        '<th>Size [voxels]</th><th>Changed</th><th>Largest moves</th></tr></thead><tbody>'];
    for i = 1:numel(steps)
        s = steps(i);
        if isempty(s.counts_before)
            changed = '&mdash;';
            moves = '&mdash;';
        else
            changed = sprintf('%d voxels (%.2f mL; %.2f%%)', s.n_changed, s.n_changed * ml, ...
                100 * s.n_changed / prod(s.size));
            moves = top_moves(s, lab, ml, 3);
        end
        html = [html sprintf('<tr><td>%d</td><td><a href="#step-%d">%s</a></td><td>%s</td><td>%s</td><td>%s</td></tr>', ...
            i, i, html_utils.escape(s.title), ...
            sprintf('%d&nbsp;&times;&nbsp;%d&nbsp;&times;&nbsp;%d', s.size), changed, moves)]; %#ok<AGROW>
    end
    html = [html '</tbody></table>'];
end

function s = top_moves(step, lab, ml, n)
    T = step.transitions;
    if isempty(T) || ~any(T(:)), s = 'none'; return; end
    [v, idx] = sort(T(:), 'descend');
    k = min(n, nnz(v));
    parts = cell(1, k);
    for q = 1:k
        [r, c] = ind2sub(size(T), idx(q));
        parts{q} = sprintf('%s &rarr; %s %.2f mL', html_utils.escape(label_name(lab, 'medium', r-1)), ...
            html_utils.escape(label_name(lab, 'medium', c-1)), v(q) * ml);
    end
    s = strjoin(parts, '<br>');
end

function html = build_steps_section(steps, lab, info)
    ml = info.resolution_mm^3 / 1000;
    html = ['<div class="segqc-controls">' ...
        '<label>Plane <select id="segqc-plane">' ...
        '<option value="1">i fixed (j &times; k)</option>' ...
        '<option value="2" selected>j fixed (i &times; k)</option>' ...
        '<option value="3">k fixed (i &times; j)</option></select></label>' ...
        '<label>Size <input type="range" id="segqc-size" min="160" max="720" step="20" value="320"></label>' ...
        '<span class="note">Slices pass through the focus (the shared head model: through the volume centre). ' ...
        'In rotated grids k is the beam axis; in RAS+ grids i, j, k are left&ndash;right, ' ...
        'posterior&ndash;anterior, inferior&ndash;superior. Hover for voxel and tissue.</span></div>'];
    for i = 1:numel(steps)
        s = steps(i);
        html = [html sprintf('<div class="segqc-step" id="step-%d"><h3>%d. %s</h3>', i, i, html_utils.escape(s.title))]; %#ok<AGROW>
        html = [html sprintf('<p>%s</p><p class="note">Grid: %s; %d &times; %d &times; %d voxels; slice through voxel [%d %d %d].</p>', ...
            html_utils.escape(s.description), html_utils.escape(s.grid), s.size, s.ref_pos)]; %#ok<AGROW>
        if ~isempty(s.notes)
            html = [html sprintf('<p class="note">%s</p>', html_utils.escape(s.notes))]; %#ok<AGROW>
        end
        html = [html sprintf('<div class="segqc-panels" data-step="%d"></div>', i - 1)]; %#ok<AGROW>
        html = [html legend_html(s, lab)]; %#ok<AGROW>
        if ~isempty(s.transitions) && any(s.transitions(:))
            html = [html transitions_table(s, lab, ml)]; %#ok<AGROW>
        elseif ~isempty(s.counts_before)
            html = [html '<p class="note">No voxel changed tissue in this step.</p>']; %#ok<AGROW>
        end
        html = [html '</div>']; %#ok<AGROW>
    end
end

function html = legend_html(s, lab)
    space = s.label_space;
    present = find(s.counts_after > 0) - 1;
    if ~isempty(s.counts_before)
        present = union(present, find(s.counts_before > 0) - 1);
    end
    items = arrayfun(@(v) sprintf('<span class="segqc-key"><i style="background:%s"></i>%s</span>', ...
        colour_of(lab, space, v), html_utils.escape(label_name(lab, space, v))), present, 'UniformOutput', false);
    html = ['<div class="segqc-legend">' strjoin(items, '') '</div>'];
end

function c = colour_of(lab, space, v)
    cols = lab.(space).colours;
    if v + 1 <= numel(cols); c = cols{v+1}; else; c = '#888888'; end
end

function html = transitions_table(s, lab, ml)
    T = s.transitions;
    [r, c, v] = find(T);
    [v, o] = sort(v, 'descend'); r = r(o); c = c(o);
    html = ['<table class="data-table segqc-moves"><thead><tr><th>From</th><th>To</th>' ...
        '<th>Voxels</th><th>Volume [mL]</th><th>Share of the source tissue</th></tr></thead><tbody>'];
    for q = 1:numel(v)
        from_total = s.counts_before(r(q));
        html = [html sprintf('<tr><td>%s</td><td>%s</td><td>%d</td><td>%.3f</td><td>%.2f%%</td></tr>', ...
            html_utils.escape(label_name(lab, 'medium', r(q)-1)), html_utils.escape(label_name(lab, 'medium', c(q)-1)), ...
            v(q), v(q) * ml, 100 * v(q) / max(from_total, 1))]; %#ok<AGROW>
    end
    html = [html '</tbody></table>'];
end

function html = build_volumes_section(steps, lab, info)
    ml = info.resolution_mm^3 / 1000;
    keep = arrayfun(@(s) strcmp(s.label_space, 'medium'), steps);
    S = steps(keep);
    idx = find(keep);
    if isempty(S)
        html = '<p class="placeholder">No medium-label steps recorded.</p>';
        return
    end
    K = max(arrayfun(@(s) numel(s.counts_after), S));
    html = ['<p>Volume of each medium tissue after each step [mL]. The grid crop removes volume ' ...
        'outside the simulation grid, so its column is not comparable with the others.</p>' ...
        '<table class="data-table"><thead><tr><th>Tissue</th>'];
    for i = 1:numel(S)
        html = [html sprintf('<th>%d. %s</th>', idx(i), html_utils.escape(S(i).title))]; %#ok<AGROW>
    end
    html = [html '</tr></thead><tbody>'];
    for v = 0:K-1
        vals = arrayfun(@(s) cnt(s.counts_after, v), S);
        if ~any(vals), continue; end
        html = [html sprintf('<tr><td>%s</td>', html_utils.escape(label_name(lab, 'medium', v)))]; %#ok<AGROW>
        html = [html sprintf('<td>%.2f</td>', vals * ml)]; %#ok<AGROW>
        html = [html '</tr>']; %#ok<AGROW>
    end
    html = [html '</tbody></table>'];
end

function n = cnt(c, v)
    if v + 1 <= numel(c); n = c(v+1); else; n = 0; end
end

function html = build_settings_section(parameters)
    html = '<h3>Head model (<code>headmodel</code>)</h3><table class="info-table">';
    if isfield(parameters, 'headmodel')
        f = fieldnames(parameters.headmodel);
        for i = 1:numel(f)
            v = parameters.headmodel.(f{i});
            if islogical(v); v = double(v); end
            html = [html kv(f{i}, html_utils.format_cell(v))]; %#ok<AGROW>
        end
    end
    html = [html kv('grid.resolution_mm', html_utils.format_cell(parameters.grid.resolution_mm))];
    if isfield(parameters.grid, 'mode')
        html = [html kv('grid.mode', html_utils.escape(parameters.grid.mode))];
    end
    html = [html '</table>'];
    if isfield(parameters, 'layers')
        cs = charm_seg_labels();
        cn = fieldnames(cs);
        html = [html '<h3>Tissue mapping (<code>layers</code>)</h3><table class="data-table"><thead>' ...
            '<tr><th>Medium tissue</th><th>charm labels</th></tr></thead><tbody>'];
        L = fieldnames(parameters.layers);
        for i = 1:numel(L)
            vals = parameters.layers.(L{i});
            names = arrayfun(@(v) charm_name(cs, cn, v), vals(:)', 'UniformOutput', false);
            html = [html sprintf('<tr><td>%s</td><td>%s</td></tr>', html_utils.escape(L{i}), ...
                html_utils.escape(strjoin(names, ', ')))]; %#ok<AGROW>
        end
        html = [html '</tbody></table><p class="note">Layers are assigned in this order; ' ...
            'a later layer overwrites an earlier one where their smoothed masks overlap.</p>'];
    end
end

function n = charm_name(cs, cn, v)
    n = sprintf('%d', v);
    for i = 1:numel(cn)
        x = cs.(cn{i});
        if isscalar(x) && x == v
            n = sprintf('%d (%s)', v, cn{i});
            return
        end
    end
end

% ── Viewer ─────────────────────────────────────────────────────────────
function d = viewer_data(steps, lab)
    d = struct();
    d.palettes = struct('medium', {lab.medium.colours}, 'charm', {lab.charm.colours});
    d.names = struct('medium', {lab.medium.names}, 'charm', {lab.charm.names});
    st = cell(1, numel(steps));
    for i = 1:numel(steps)
        s = steps(i);
        planes = cell(1, 3);
        for p = 1:3
            a = s.slices_after{p};
            pl = struct('w', size(a, 1), 'h', size(a, 2), 'after', rle(a), 'before', '');
            if ~isempty(s.slices_before)
                pl.before = rle(s.slices_before{p});
            end
            planes{p} = pl;
        end
        st{i} = struct('space', s.label_space, 'size', s.size, 'ref', s.ref_pos, ...
            'has_before', ~isempty(s.slices_before), 'planes', {planes});
    end
    d.steps = st;
end

function e = rle(S)
% Row-major (top row = highest second index) run-length code of a label
% slice: base64 of the uint8 values and of the uint16 run lengths
    R = fliplr(S);                 % R(:): image rows top-down, each row left to right
    v = uint8(R(:));
    starts = [1; find(diff(double(v)) ~= 0) + 1];
    lens = diff([starts; numel(v) + 1]);
    vals = v(starts);
    % split runs longer than uint16
    if any(lens > 65535)
        nv = {}; nl = {};
        for k = 1:numel(lens)
            L = lens(k);
            while L > 65535
                nv{end+1} = vals(k); nl{end+1} = 65535; L = L - 65535; %#ok<AGROW>
            end
            nv{end+1} = vals(k); nl{end+1} = L; %#ok<AGROW>
        end
        vals = uint8([nv{:}])'; lens = [nl{:}]';
    end
    lb = typecast(uint16(lens(:))', 'uint8');
    if strcmp(endian(), 'B'); lb = reshape(flipud(reshape(lb, 2, [])), 1, []); end
    e = struct('v', matlab.net.base64encode(vals(:)'), 'n', matlab.net.base64encode(lb));
end

function e = endian()
    [~, ~, e] = computer();
end

