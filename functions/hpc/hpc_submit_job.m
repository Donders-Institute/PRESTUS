function [job_id, parameters] = hpc_submit_job(hpc_type, temp_m_file, parameters, log_dir)
% HPC_SUBMIT_JOB  Write a scheduler script and submit a MATLAB job to SLURM or qsub
%
% Generates a temporary scheduler script (SLURM .sh or PBS .sh) from the
% parameters struct, submits it, and returns the assigned job ID. Also handles
% Snellius-specific parameter extraction when parameters.hpc.name = 'snellius'.
% The second output (parameters) is returned because Snellius extraction may
% modify hpc fields in place.
%
% Use as:
%   [job_id, parameters] = hpc_submit_job(hpc_type, temp_m_file, parameters, log_dir)
%
% Input:
%   hpc_type    - 'slurm' or 'qsub'
%   temp_m_file - basename of the temporary .m script (no path, no extension);
%                 generated by hpc_setup_temp_files
%   parameters  - PRESTUS config struct; relevant fields:
%                   .subject_id, .hpc.name, .hpc.partition, .hpc.gpu,
%                   .hpc.reservation, .hpc.exclude, .hpc.cores, .hpc.memorylimit,
%                   .hpc.timelimit, .hpc.job_name, .hpc.job_prefix,
%                   .hpc.depend_job_id(s), .hpc.depend_type
%   log_dir     - log directory; the job runs and writes its logs there
%
% Output:
%   job_id     - scheduler job ID (numeric for SLURM, string for qsub)
%   parameters - (possibly modified) parameters struct; hpc fields may be
%                updated by Snellius-specific extraction
%
% See also: HPC_DETECT_SYSTEM, HPC_SETUP_TEMP_FILES, HPC_WAIT_FOR_COMPLETION

switch hpc_type
    case 'slurm'
        temp_slurm_path = fullfile(log_dir, sprintf('temp_slurm_%s.sh', datestr(now, 'yyyymmdd_HHMMSS')));

        % Define HPC type
	    if ~isfield(parameters.hpc, 'name')
            parameters.hpc.name = 'default';
        end
    
	    % Overwrite and extract additional parameters if Snellius HPC
	    if strcmp(parameters.hpc.name, 'snellius')
		    [parameters] = extract_snellius_parameters(parameters);
	    end
        
        write_slurm_script(temp_slurm_path, parameters, temp_m_file, log_dir);
        job_id = submit_slurm_job(temp_slurm_path, log_dir);

    case 'qsub'
        temp_qsub_path = fullfile(log_dir, sprintf('temp_qsub_%s.sh', datestr(now, 'yyyymmdd_HHMMSS')));
        write_qsub_script(temp_qsub_path, parameters, temp_m_file, log_dir);
        job_id = submit_qsub_job(temp_qsub_path, log_dir);

    otherwise
        error('Unsupported HPC type: %s', hpc_type);
end

% qsub returns the ID as text (e.g. '12345.server'); sprintf('%d') would print its char codes
if ischar(job_id) || isstring(job_id)
    job_text = char(job_id);
else
    job_text = sprintf('%d', job_id);
end
fprintf('Job "%s" (ID: %s) submitted successfully\n', hpc_job_name(parameters), job_text);
if strcmp(hpc_type, 'slurm')
    fprintf('Monitor: squeue --user $USER -o "%%.18i %%.9P %%.50j %%.8u %%.2t %%.10M %%.6D %%R"\n');
end

% ========== LOCAL FUNCTIONS ==========
function write_slurm_script(temp_slurm_path, parameters, temp_m_file, log_dir)
    subj_id_string = sprintf('sub-%03d', parameters.subject_id);
    job_name = hpc_job_name(parameters);
	
    fid = fopen(temp_slurm_path, 'w+');
    fprintf(fid, '#!/bin/bash\n');
    fprintf(fid, '#SBATCH --job-name=%s\n', job_name);
    
    % Partition & GPU detection
    needs_gpu = job_needs_gpu(parameters);
    
    if isfield(parameters.hpc, 'partition') && ~isempty(strtrim(char(parameters.hpc.partition)))
        fprintf(fid, '#SBATCH --partition=%s\n', strtrim(char(parameters.hpc.partition)));
    elseif needs_gpu
        fprintf(fid, '#SBATCH --partition=gpu\n');
    end

    if strcmp(parameters.hpc.name, 'snellius')
		fprintf(fid, '#SBATCH --gpus=%i\n', parameters.hpc.n_gpu);
    elseif isfield(parameters.hpc, 'gpu') && ~isempty(strtrim(char(parameters.hpc.gpu)))
        fprintf(fid, '#SBATCH --gres=%s\n', strtrim(char(parameters.hpc.gpu)));
    elseif needs_gpu
        fprintf(fid, '#SBATCH --gres=gpu:1\n');
    end

    if isfield(parameters.hpc, 'reservation') && ~isempty(strtrim(char(parameters.hpc.reservation)))
        fprintf(fid, '#SBATCH --reservation=%s\n', strtrim(char(parameters.hpc.reservation)));
    end

    % Nodes to avoid, e.g. a node whose GPU is held by a stale process.
    if isfield(parameters.hpc, 'exclude') && ~isempty(strtrim(char(parameters.hpc.exclude)))
        fprintf(fid, '#SBATCH --exclude=%s\n', strtrim(char(parameters.hpc.exclude)));
    end

    % Snellius presets always set hpc.cores; elsewhere it is optional ([] = cluster default)
    if isfield(parameters.hpc, 'cores') && ~isempty(parameters.hpc.cores)
        fprintf(fid, '#SBATCH --cpus-per-task=%i\n', parameters.hpc.cores);
    end

    fprintf(fid, '#SBATCH --mem=%iG\n', parameters.hpc.memorylimit);
    % Node-local disk for the k-Wave .h5 files (HPC_SCRATCH_SETUP)
    if isfield(parameters.hpc, 'tmp_gb') && ~isempty(parameters.hpc.tmp_gb) && parameters.hpc.tmp_gb > 0
        fprintf(fid, '#SBATCH --tmp=%iG\n', ceil(parameters.hpc.tmp_gb));
    end
    fprintf(fid, '#SBATCH --time=%s\n', parameters.hpc.timelimit);
    fprintf(fid, '#SBATCH --output=%s_slurm_output_%%j.log\n', subj_id_string);
    fprintf(fid, '#SBATCH --error=%s_slurm_error_%%j.log\n', subj_id_string);
    fprintf(fid, '#SBATCH --chdir=%s\n', log_dir);

    % Job dependencies (used by uncertainty pipeline for stage chaining).
    % --kill-on-invalid-dep=yes ensures that if the predecessor fails or is
    % cancelled, all dependent jobs are automatically cancelled rather than
    % remaining stuck as DependencyNeverSatisfied indefinitely.
    % hpc.depend_type: 'afterok' (default) or 'afterany' (e.g. a study's group
    % report, which should run even when some subject jobs failed).
    dep_type = dependency_type(parameters);
    if isfield(parameters.hpc, 'depend_job_ids') && ~isempty(parameters.hpc.depend_job_ids)
        dep_str = strjoin(arrayfun(@(x) num2str(x), parameters.hpc.depend_job_ids, ...
            'UniformOutput', false), ':');
        fprintf(fid, '#SBATCH --dependency=%s:%s\n', dep_type, dep_str);
        fprintf(fid, '#SBATCH --kill-on-invalid-dep=yes\n');
    elseif isfield(parameters.hpc, 'depend_job_id') && ~isempty(parameters.hpc.depend_job_id)
        fprintf(fid, '#SBATCH --dependency=%s:%d\n', dep_type, parameters.hpc.depend_job_id);
        fprintf(fid, '#SBATCH --kill-on-invalid-dep=yes\n');
    end
    
    if needs_gpu, fprintf(fid, 'nvidia-smi\n'); end
    % CPU model and allocation in the job log (timing comparisons need the hardware)
    fprintf(fid, 'echo "CPU model: $(lscpu | sed -n ''s/^Model name:[[:space:]]*//p'' | head -1)"\n');
    fprintf(fid, 'echo "CPUs allocated: ${SLURM_CPUS_PER_TASK:-default}"\n');
	if strcmp(parameters.hpc.name, 'snellius')
        fprintf(fid, 'module load 2024\n');
        fprintf(fid, 'module load MATLAB/2024b\n');
    else
		fprintf(fid, 'module load matlab/R2023b\n');
	end
    write_run_type(fid);
    fprintf(fid, 'matlab -batch "%s"\n', temp_m_file);
    fclose(fid);
end

function [parameters] = extract_snellius_parameters(parameters)
	
    switch parameters.hpc.partition
        case 'gpu_a100'
            parameters.hpc.memorylimit = parameters.snellius.gpu_a100.memorylimit;
            parameters.hpc.cores = parameters.snellius.gpu_a100.cores;
            max_timelimit = parameters.snellius.gpu_a100.timelimit;
            parameters.hpc.n_gpu = parameters.snellius.gpu_a100.n_gpu;
        case 'gpu_h100'
            parameters.hpc.memorylimit = parameters.snellius.gpu_h100.memorylimit;
            parameters.hpc.cores = parameters.snellius.gpu_h100.cores;
            max_timelimit = parameters.snellius.gpu_h100.timelimit;
            parameters.hpc.n_gpu = parameters.snellius.gpu_h100.n_gpu;
        otherwise
            error('GPU %s is unknown or not implemented for Snellius.', parameters.hpc.partition)
    end

    assert(walltime_seconds(parameters.hpc.timelimit) <= walltime_seconds(max_timelimit), ...
        'Maximum wall time of %s is exceeded (%s).', ...
        max_timelimit, ...
        parameters.hpc.timelimit)
end

function s = walltime_seconds(t)
    % '[D-]HH:MM:SS' (also MM:SS or plain minutes, as SLURM accepts) -> seconds
    t = strtrim(char(string(t)));
    days = 0;
    tok = regexp(t, '^(\d+)-(.*)$', 'tokens', 'once');
    if ~isempty(tok)
        days = str2double(tok{1});
        t = tok{2};
    end
    parts = str2double(strsplit(t, ':'));
    if any(isnan(parts)) || numel(parts) > 3
        error('hpc_submit_job:badTimelimit', 'Cannot parse wall time "%s" (expected HH:MM:SS).', t);
    end
    switch numel(parts)
        case 1, s = parts * 60;
        case 2, s = parts(1) * 60 + parts(2);
        case 3, s = parts(1) * 3600 + parts(2) * 60 + parts(3);
    end
    s = s + days * 86400;
end

function write_run_type(fid)
    % The job reports telemetry with the submitting session's run type
    % (TELEMETRY_RUN_TYPE). sbatch/qsub start from the environment MATLAB
    % was launched with, so a setenv in this session (run_all_tests, a
    % benchmark setup) would not reach the job otherwise. Only the two
    % whitelisted values are written; 'deployment' is the default anyway.
    rt = telemetry_run_type();
    if ~strcmp(rt, 'deployment')
        fprintf(fid, 'export PRESTUS_RUN_TYPE=%s\n', rt);
    end
end

function job_id = submit_slurm_job(temp_slurm_path, log_dir)
    % run_command invokes sbatch directly via argv, no shell at all --
    % log_dir/temp_slurm_path reach the process as literal arguments
    % regardless of their contents.
    fprintf('SLURM command: sbatch --parsable %s (in %s)\n', temp_slurm_path, log_dir);
    [status, out] = run_command({'sbatch', '--parsable', temp_slurm_path}, 'WorkingDir', log_dir);
    if status ~= 0, error('SLURM submission failed: %s', out); end

    job_id = parse_sbatch_job_id(out);
    if isnan(job_id), error('No SLURM job ID returned:\n%s', out); end
end

function write_qsub_script(temp_qsub_path, parameters, temp_m_file, log_dir)
    subj_id_string = sprintf('sub-%03d', parameters.subject_id);
    job_name = hpc_job_name(parameters);
    
    needs_gpu = job_needs_gpu(parameters);

    fid = fopen(temp_qsub_path, 'w+');
    fprintf(fid, '#!/bin/bash\n');
    fprintf(fid, '#PBS -N %s\n', job_name);
    if needs_gpu
        fprintf(fid, '#PBS -l nodes=1:gpus=1,feature=cuda,reqattr=cudacap>=8.0,mem=%iGb,walltime=%s\n', ...
            parameters.hpc.memorylimit, char(parameters.hpc.timelimit));
    else
        fprintf(fid, '#PBS -l nodes=1,mem=%iGb,walltime=%s\n', ...
            parameters.hpc.memorylimit, char(parameters.hpc.timelimit));
    end
    fprintf(fid, '#PBS -d %s\n', log_dir);

    % Job dependencies (used by uncertainty pipeline for stage chaining)
    dep_type = dependency_type(parameters);
    if isfield(parameters.hpc, 'depend_job_ids') && ~isempty(parameters.hpc.depend_job_ids)
        dep_str = strjoin(arrayfun(@(x) num2str(x), parameters.hpc.depend_job_ids, ...
            'UniformOutput', false), ':');
        fprintf(fid, '#PBS -W depend=%s:%s\n', dep_type, dep_str);
    elseif isfield(parameters.hpc, 'depend_job_id') && ~isempty(parameters.hpc.depend_job_id)
        fprintf(fid, '#PBS -W depend=%s:%d\n', dep_type, parameters.hpc.depend_job_id);
    end
    % PBS does not expand a job ID in #PBS -o/-e, so the script body
    % redirects its output to per-job logs named as for SLURM.
    fprintf(fid, 'exec >"%s_qsub_output_${PBS_JOBID}.log" 2>"%s_qsub_error_${PBS_JOBID}.log"\n', ...
        subj_id_string, subj_id_string);
	fprintf(fid, 'module load matlab/R2022b\n');   % PBS nodes support CUDA 11.2 only, dropped from R2023 on
    write_run_type(fid);
    fprintf(fid, 'matlab -batch "%s"\n', temp_m_file);
    fclose(fid);
end

function job_id = submit_qsub_job(temp_qsub_path, log_dir)
    % run_command invokes qsub directly via argv, no shell at all.
    fprintf('qsub command: qsub %s (in %s)\n', temp_qsub_path, log_dir);
    [status, out] = run_command({'qsub', temp_qsub_path}, 'WorkingDir', log_dir);
    if status ~= 0, error('qsub submission failed: %s', out); end
    job_id = strtrim(out);
end
end

function tf = job_needs_gpu(parameters)
% True when a solver the job runs computes on a GPU:
%   k-Wave (acoustic kwave/kwave_elastic, thermal kwave with heating, time
%     reversal) with simulation.code_type 'matlab_gpu' or 'cpp_gpu';
%   jwave (acoustic) unless jwave.use_gpu is false (empty = auto-detect);
%   BabelBrain (acoustic or thermal) unless babelbrain.computing_backend is
%     'cpu' / 4 (its thermal engine has no CPU backend).
    acoustic = lower(char(field_or(parameters, {'acoustic_backend'}, 'kwave')));
    thermal = lower(char(field_or(parameters, {'thermal_backend'}, 'kwave')));
    heating = logical(field_or(parameters, {'modules', 'run_heating_sims'}, 0));
    reverse = logical(field_or(parameters, {'time_reversal', 'enabled'}, false));

    kwave_runs = any(strcmp(acoustic, {'kwave', 'kwave_elastic'})) || ...
        (strcmp(thermal, 'kwave') && heating) || reverse;
    code_type = char(field_or(parameters, {'simulation', 'code_type'}, ''));
    tf = kwave_runs && any(strcmp(code_type, {'matlab_gpu', 'cpp_gpu'}));

    if strcmp(acoustic, 'jwave')
        use_gpu = field_or(parameters, {'jwave', 'use_gpu'}, []);
        tf = tf || isempty(use_gpu) || logical(use_gpu);
    end

    if strcmp(acoustic, 'babelbrain') || (strcmp(thermal, 'babelbrain') && heating)
        backend = field_or(parameters, {'babelbrain', 'computing_backend'}, 'auto');
        on_cpu = (isnumeric(backend) && isequal(backend, 4)) || ...
            ((ischar(backend) || isstring(backend)) && strcmpi(backend, 'cpu'));
        tf = tf || ~on_cpu;
    end
end

function v = field_or(s, path, default)
% Nested field s.(path{1}).(path{2})..., or default when absent, empty, or a
% YAML null ('~' loads as a yaml.Null object, which isempty does not catch).
    v = default;
    for k = 1:numel(path)
        if ~isstruct(s) || ~isfield(s, path{k}), return; end
        s = s.(path{k});
    end
    if ~isempty(s) && ~isa(s, 'yaml.Null'), v = s; end
end

function dep_type = dependency_type(parameters)
% Scheduler dependency type for depend_job_id(s): 'afterok' unless
% parameters.hpc.depend_type says 'afterany'.
    dep_type = 'afterok';
    if isfield(parameters.hpc, 'depend_type') && ~isempty(parameters.hpc.depend_type)
        dep_type = char(parameters.hpc.depend_type);
        assert(any(strcmp(dep_type, {'afterok', 'afterany'})), ...
            'hpc.depend_type must be ''afterok'' or ''afterany'' (got ''%s'').', dep_type);
    end
end
